/* Pixel art from rows of characters: each character is a colour from the map, "." is empty. */
function pixels(rows, x, y, s, colors){
  const paths = {};
  rows.forEach((r, j) => [...r].forEach((ch, i) => { if (colors[ch]) (paths[ch] ||= []).push(`M${x + i * s} ${y + j * s}h${s}v${s}h-${s}z`); }));
  return Object.entries(paths).map(([ch, d]) => `<path d="${d.join('')}" fill="${colors[ch]}"/>`).join('');
}
